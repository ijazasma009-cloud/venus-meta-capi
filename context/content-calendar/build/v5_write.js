const POST = {
  type: 'object',
  properties: {
    id: { type: 'integer' },
    date: { type: 'string' },
    conceptLine: { type: 'string', description: 'One sentence naming the creative idea, written for the client to read and instantly get it.' },
    hook: { type: 'string', description: 'The words that appear on screen first, or slide 1 text.' },
    caption: { type: 'string', description: 'Full caption in the required shape and register, with real line breaks.' },
    hashtags: { type: 'string', description: '3 to 5 hashtags' },
    spec: { type: 'string', description: 'NUMBERED POINTERS. Slide by slide for designed posts, step by step for video edits. Specific colours, positions, exact on-screen words, timings.' },
    recordGuide: { type: 'string', description: 'NUMBERED: who, where, kit, props, the beat, direction, time on set. Only if it needs shooting, else empty string.' },
    reference: { type: 'string', description: 'A real format-matched URL from the library, or empty string' },
    refWhy: { type: 'string', description: 'One line on exactly what to copy from it' },
  },
  required: ['id','date','conceptLine','hook','caption','hashtags','spec','recordGuide','reference','refWhy'],
}
const WEEK = { type: 'object', properties: { posts: { type: 'array', items: POST } }, required: ['posts'] }
const CHECK = {
  type: 'object',
  properties: {
    week: { type: 'integer' },
    problems: { type: 'array', items: { type: 'object', properties: {
      postId: { type: 'integer' }, issue: { type: 'string' }, quote: { type: 'string' }, fix: { type: 'string' } },
      required: ['postId','issue','quote','fix'] } },
  },
  required: ['week','problems'],
}

const weeks = (typeof args !== 'undefined' && args && args.weeks) || WEEKS

phase('Write')
log(`Writing ${weeks.length} weeks, ${weeks.reduce((n, w) => n + w.rows.length, 0)} idea-led posts`)

const done = await pipeline(
  weeks,
  w => agent(`${BRIEF}\n${REFS}\n\n=== WEEK ${w.week}. Write these 7 posts. ===

Each row gives you a CONCEPT. That concept is the post. Build the caption and the brief around it.

${w.rows.map(r => `
ROW ${r.id}  ${r.date} (${r.dayFull})
  BUCKET: ${r.bucket} / ${r.format}      FORMAT: ${r.creative}      VOICE: ${r.voice}
  CONCEPT: ${r.concept}
  ${r.conceptNote ? 'WHY IT WORKS: ' + r.conceptNote : ''}
  SOURCE: ${r.source}${r.marker ? '\n  NOTE: ' + r.marker : ''}${r.asset ? `\n  FOOTAGE YOU HAVE: ${r.asset.driveName}, ${r.asset.dur} seconds, ${r.asset.treat}${r.asset.model ? ', model ' + r.asset.model : ''}` : ''}${r.frameSource ? `\n  PULL STILL FRAMES FROM: ${r.frameSource}` : ''}${r.watchedDesc ? `\n  WHAT IS ACTUALLY IN THE CLIP: ${r.watchedDesc}` : ''}${r.defect ? `\n  MUST FIX IN THE EDIT: ${r.defect}` : ''}`).join('\n')}

RULES FOR THIS WEEK:
- SOURCE DRIVE_EDIT or DRIVE_READY means the footage exists. Write the spec as numbered edit steps.
  Never reduce a long clip to a stub. A 45 second file supports a 30 to 35 second cut.
- SOURCE SHOOT_PROP or SHOOT_ENGAGE means it must be filmed. Write a full numbered recordGuide.
  Keep every shoot under 25 minutes with a phone and no crew. Name every prop.
- SOURCE DESIGN means a graphic or carousel. Write it slide by slide with numbered pointers.
- Every hook must differ from every other hook this week.
- Never mention Venus Glow, HydraFacial or any facial treatment.
- The concept is the point. If your caption would work equally well without the concept, rewrite it.`,
    { label: `w${w.week}`, phase: 'Write', schema: WEEK }),
  (out, w) => {
    if (!out || !out.posts) return null
    const body = out.posts.map(p => `POST ${p.id}\nCONCEPT: ${p.conceptLine}\nHOOK: ${p.hook}\nCAPTION:\n${p.caption}\nTAGS: ${p.hashtags}\nSPEC:\n${p.spec}\nGUIDE:\n${p.recordGuide}\nREF: ${p.reference}`).join('\n\n')
    return agent(`Check this week of Instagram posts for a Pakistani aesthetic clinic. Report every problem.

CHECK FOR:
1. Roman Urdu anywhere (Urdu in Latin letters).
2. Em dashes.
3. Any mention of Venus Glow, HydraFacial, or a facial treatment. The client banned these entirely.
4. Any discount, sale, percentage off, offer or price.
5. Botox or any botulinum brand name.
6. The words permanent, painless, guaranteed, flawless, miracle.
7. "hair removal" used as a claim rather than "hair reduction", outside a search keyword block.
8. Dr. Uzair named in a hook or in the first line of a caption.
9. Engagement bait: "comment YES", "tag a friend", "tag someone", "double tap".
10. A statistic, study, citation, regulator or AQI reading appearing IN A CAPTION. Captions must be
    warm and simple. Facts belong in the brief, never in the caption.
11. A caption body over 70 words, not counting the location block and hashtags.
12. More than 5 hashtags.
13. A spec written as prose paragraphs instead of numbered pointers.
14. A spec that is vague: no colours, no positions, no exact on-screen words, no timings.
15. A post whose caption would read the same if the creative concept were removed. That means the
    concept was not executed.
16. A reference URL not in the supplied library, or a reel referencing a carousel or vice versa.
17. An invented patient quote or a named result.

WEEK ${w.week}:
${body}

Report each problem with the post id, the issue, the exact quote and a concrete fix. Empty array if clean.`,
      { label: `check w${w.week}`, phase: 'Check', schema: CHECK, effort: 'high' })
      .then(v => ({ week: w.week, posts: out.posts, check: v }))
  }
)

const ok = done.filter(Boolean)
const posts = ok.reduce((n, w) => n + w.posts.length, 0)
const probs = ok.reduce((n, w) => n + ((w.check && w.check.problems) || []).length, 0)
log(`${ok.length} weeks, ${posts} posts, ${probs} problems flagged`)

return {
  weeks: ok.map(w => ({ week: w.week, posts: w.posts })),
  problems: ok.flatMap(w => ((w.check && w.check.problems) || []).map(p => ({ week: w.week, ...p }))),
  stats: { weeks: ok.length, posts, problems: probs },
}
